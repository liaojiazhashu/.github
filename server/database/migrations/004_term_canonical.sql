-- =============================================================================
-- 004 词库条目分「通行词」与「专名」
-- -----------------------------------------------------------------------------
-- 背景：003 收窄了分类，但没有解决更根本的问题 —— 词本身还是原文专名。
-- 15 篇作品产出的 75 个关键词，**每一个都只关联 1 篇作品**：
--   35号目的地、WA0409黑洞、封孔泥、《园艺与花卉》、巧克力罐、太阳能热水器……
-- 这类词进了词库，"拿着概念找作品" 就不成立：点进去永远只有一篇。
--
-- 004 配合 S1 v3 提示词做两件事：
--   1) 提示词与闸门要求模型优先从 resources/taxonomy/sf_terms.php 的 186 个
--      通行词里选，专名（编号、书名、长短语）直接丢弃；
--   2) 本迁移给词条加 is_canonical，标出「这个词是人工审过的通行词」。
--
-- 公开词库的口径随之变成：
--   is_canonical = 1  OR  被 ≥2 篇已发布作品引用
-- 即：通行词哪怕暂时只有一篇引用，也该出现在词库里（它本来就是通用概念）；
-- 表外新词必须靠第二篇作品投票证明自己，否则只是一条挂着单篇的死词。
-- 词条本身仍不删 —— 作品发回来它自己就活了。
--
-- 撤回：004_term_canonical_rollback.sql（只删列，不动数据）
-- =============================================================================

ALTER TABLE hq_index_term
  ADD COLUMN is_canonical TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '1=通行词表内的规范词；0=模型新建，需 ≥2 篇作品引用才进公开词库'
    AFTER category;

-- 回填：把词表里已经存在的词标出来（当前 75 个专名应全部为 0）
UPDATE hq_index_term SET is_canonical = 0 WHERE is_canonical = 1;

-- 索引：词库总览按 is_canonical 过滤，与 status/category 常一起用
CREATE INDEX idx_term_canon ON hq_index_term (status, is_canonical);
